# ## 5 · The contribution table (6')
#
# ✏️ **Exercise** · Return one row per kind of context (`synonyms`, `descriptions`, `examples`) with the drop in
# accuracy from `full` overall, in Arabic and in English, the area that dropped most, and the increase in the
# wrong-but-plausible rate. Sort by overall drop.

# %%
def contribution(full: pd.DataFrame, variants: dict) -> pd.DataFrame:
    # BEGIN SOLUTION
    f_all, f_lang, f_area = D.summary(full), D.summary(full, ["lang"]), D.summary(full, ["area"])
    rows = []
    for kind, t in variants.items():
        a, l, ar = D.summary(t), D.summary(t, ["lang"]), D.summary(t, ["area"])
        drop_area = (f_area.accuracy - ar.accuracy)
        rows.append({"context": kind, "drop": round(float(f_all.accuracy.iloc[0] - a.accuracy.iloc[0]), 3),
                     "drop_ar": round(float(f_lang.accuracy["ar"] - l.accuracy["ar"]), 3),
                     "drop_en": round(float(f_lang.accuracy["en"] - l.accuracy["en"]), 3),
                     "area_most": drop_area.idxmax(), "more_plausible": round(float(a.wrong_plausible.iloc[0] - f_all.wrong_plausible.iloc[0]), 3)})
    return pd.DataFrame(rows).sort_values("drop", ascending=False).reset_index(drop=True)
    # END SOLUTION


# %%
