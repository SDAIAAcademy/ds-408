# ✏️ **Exercise** · Return, for each of the four variants, the prompt size in characters and how many metrics
# carry synonyms, descriptions and examples. Each ablation must remove exactly one kind.

# %%
def context_sizes() -> pd.DataFrame:
    # BEGIN SOLUTION
    rows = []
    for v in D.VARIANTS:
        ctx = D.context(METRICS, v)
        rows.append({"variant": v, "chars": len(json.dumps(ctx, ensure_ascii=False)),
                     "synonyms": sum("synonyms" in m for m in ctx), "descriptions": sum("description" in m for m in ctx),
                     "examples": sum("examples" in m for m in ctx)})
    return pd.DataFrame(rows).set_index("variant")
    # END SOLUTION


