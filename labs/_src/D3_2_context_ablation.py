# ✏️ **Exercise** · Score `no_synonyms`, then return `flips`: the questions whose outcome differs from the full
# configuration, with `id`, `lang`, `area`, the outcome in `full` and in the variant.

# %%
def flips(base: pd.DataFrame, other: pd.DataFrame) -> pd.DataFrame:
    # BEGIN SOLUTION
    m = base.merge(other, on=["id", "lang", "area", "difficulty", "run"], suffixes=("_full", "_variant"))
    m = m[m.outcome_full != m.outcome_variant]
    return m[["id", "lang", "area", "difficulty", "outcome_full", "outcome_variant", "got_variant", "want_full"]].reset_index(drop=True)
    # END SOLUTION


